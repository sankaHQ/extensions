SCHEMA_SQL = """-- Flat catalogue schema
CREATE TABLE widgets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL UNIQUE,
    quantity bigint NOT NULL,
    note text,
    active boolean NOT NULL
);

CREATE TABLE "orders" (
    "id" bigserial PRIMARY KEY,
    "reference" text NOT NULL,
    "total" bigint
);
"""
MODELS_TS = """export interface Widget {
  id: number;
  name: string;
  quantity: number;
  note: string | null;
  active: boolean;
}

export type Order = {
  id: number;
  reference: string;
  total: number | null;
};
"""
WIDGETS_SQL = "SELECT id, name, quantity, note, active FROM widgets ORDER BY id LIMIT $1"
ORDERS_SQL = 'SELECT "id", "reference", "total" FROM "orders" ORDER BY "id" LIMIT $1'
POOL = "const pool = new Pool({ connectionString: process.env.DATABASE_URL });"
PACKAGE_JSON = json.dumps(
    {"name": "fixture", "private": True, "dependencies": {"express": "^5.2.1", "pg": "^8.23.0"}}
)
DATABASE = {"source_framework": "express", "target_framework": "axum", "database_layer": "sqlx"}
needs_postgres = pytest.mark.skipif(
    not os.getenv("SANKA_MIGRATE_TEST_POSTGRES_DSN"),
    reason="requires an explicit SANKA_MIGRATE_TEST_POSTGRES_DSN",
)


def app_source(
    *,
    widgets_sql: str = WIDGETS_SQL,
    widgets_limit: str = "100",
    pool: str = POOL,
    pg_import: str = 'import { Pool } from "pg";',
    respond: str = "res.json(rows);",
) -> str:
    return (
        'import express from "express";\n'
        f"{pg_import}\n"
        'import type { Widget } from "./models";\n\n'
        "const app = express();\n"
        f"{pool}\n\n"
        'app.get("/health", (_req, res) => {\n  res.json({ ok: true });\n});\n\n'
        'app.get("/widgets", async (_req, res) => {\n'
        f"  const {{ rows }} = await pool.query({json.dumps(widgets_sql)}, [{widgets_limit}]);\n"
        f"  {respond}\n"
        "});\n\n"
        'app.get("/orders", async (req, res) => {\n'
        f"  const {{ rows }} = await pool.query({json.dumps(ORDERS_SQL)}, [5]);\n"
        "  return res.json(rows);\n"
        "});\n\n"
        "export default app;\n"
    )


def project(
    root: Path,
    *,
    schema: str = SCHEMA_SQL,
    models: str | None = MODELS_TS,
    app: str | None = None,
) -> Path:
    (root / "src").mkdir(exist_ok=True)
    (root / "src" / "app.ts").write_text(app_source() if app is None else app)
    models_path = root / "src" / "models.ts"
    if models is None:
        models_path.unlink(missing_ok=True)
    else:
        models_path.write_text(models)
    (root / "schema.sql").write_text(schema)
    (root / "package.json").write_text(PACKAGE_JSON)
    return root


def database_request(root: Path, command: str = "plan") -> ExtensionRequest:
    return dataclasses.replace(request(root), command=command, configuration=dict(DATABASE))


def apply(root: Path) -> Path:
    req = database_request(root)
    planned = handle(req)
    assert planned.outcome == "success", planned.error
    assert planned.data["capture"]["gaps"] == []
    result = handle(
        dataclasses.replace(
            req,
            command="apply",
            reviewed_plan_hash="runtime-reviewed-plan",
            configuration=req.configuration | {"extension_plan_hash": planned.data["plan_hash"]},
        )
    )
    assert result.outcome == "success", result.error
    return Path(str(result.data["output"]))


def gaps(root: Path, config: dict[str, str] | None = None) -> list[str]:
    return list(capture(root, configuration(dict(DATABASE) if config is None else config))["gaps"])


def schema_dsn(dsn: str, schema: str) -> str:
    """Pin one schema through ``options=-csearch_path=...`` without touching the rest of the URL."""
    base, _, query = dsn.partition("?")
    pairs = [(key, value) for key, value in parse_qsl(query) if key != "options"]
    pairs.append(("options", "-csearch_path=" + schema))
    return base + "?" + urlencode(pairs)


def test_configuration_boundaries() -> None:
    plain = configuration({})
    assert plain["database_layer"] == "none"
    assert "schema_file" not in plain
    full = configuration({"database_layer": "sqlx"})
    assert full["schema_file"] == "schema.sql"
    assert full["models_file"] == "src/models.ts"
    assert (full["database_dialect"], full["migration_tool"], full["schema_mode"]) == (
        "postgresql",
        "sqlx",
        "empty",
    )
    for config in (
        {"database_layer": "diesel"},
        {"database_layer": "sqlx", "database_dialect": "mysql"},
        {"database_layer": "sqlx", "migration_tool": "refinery"},
        {"database_layer": "sqlx", "schema_mode": "existing"},
        {"database_layer": "sqlx", "schema_file": "../schema.sql"},
        {"database_layer": "sqlx", "schema_file": "schema.txt"},
        {"database_layer": "sqlx", "models_file": "src/app.ts"},
        {"schema_file": "schema.sql"},
        {"database_layer": 1},
    ):
        with pytest.raises(ValueError):
            configuration(config)


